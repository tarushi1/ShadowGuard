/**
 * ShadowGuard AI — ChatGPT site adapter
 * ================================================================
 * The ONLY file that knows how chatgpt.com is built.
 *
 * ---- On selector stability -------------------------------------
 * We are guests in OpenAI's app. They owe us no stability and do not
 * know we exist. So instead of one selector we keep an ordered chain,
 * most-stable first, and log which tier actually matched.
 *
 * Why that ordering:
 *
 *   1. IDs and data-testid attributes are written BY HUMANS, for
 *      their own test suites. Renaming one breaks OpenAI's own CI,
 *      so they rarely change. `#prompt-textarea` survived the entire
 *      migration from <textarea> to a ProseMirror contenteditable —
 *      the element type changed, the id did not.
 *
 *   2. CSS class names are GENERATED by build tools and get hashed
 *      or reordered on any refactor. Never anchor to them.
 *
 *   3. Structural selectors ("the contenteditable inside the form")
 *      describe intent rather than naming, so they survive renames —
 *      but they are ambiguous and can match the wrong thing.
 *
 * A drop from tier 1 to tier 3 is an early warning that ChatGPT
 * shipped a redesign, printed in the console before anything
 * actually breaks. Silent degradation is the failure mode we most
 * need to avoid: a DLP tool that quietly stops detecting is worse
 * than no DLP tool, because people still trust it.
 */

(() => {
  "use strict";

  SG.registerAdapter({
    id: "chatgpt",
    label: "ChatGPT",

    // Exact hostnames. Must stay in sync with manifest "matches".
    hosts: ["chatgpt.com", "chat.openai.com"],

    selectors: {
      /**
       * The message box the user types into.
       * Today this is a ProseMirror contenteditable <div>; it used to
       * be a <textarea>. Both shapes are covered, which is why
       * readText() below has to handle each.
       */
      composer: [
        "#prompt-textarea",                          // 1 — stable id, either element type
        'div.ProseMirror[contenteditable="true"]',   // 2 — rich editor implementation
        'form [contenteditable="true"]',             // 3 — structural, rich editor
        'textarea[name="prompt-textarea"]',          // 4 — named plain-textarea variant
        "form textarea",                             // 5 — structural, plain
        '[contenteditable="true"]',                  // 6 — last resort, page-wide
      ],

      /**
       * The submit control — the arrow button beside the composer.
       *
       * ChatGPT swaps this button for a STOP button while a reply is
       * streaming, which is why nothing in this codebase ever holds a
       * reference to it. We re-identify it per click instead.
       */
      sendButton: [
        'button[data-testid="send-button"]',
        "#composer-submit-button",
        'form button[type="submit"]',
      ],
    },

    /**
     * Locate the send button in the document, for programmatic use.
     *
     * Distinct from matchSendButton(), which answers "did this click
     * come from the button?" and walks UP from an event target. This
     * one walks the document DOWN to find it.
     *
     * Two exclusions matter:
     *
     *   - While a reply streams, ChatGPT replaces the send button
     *     with a STOP button. Tier 1 and 2 stop matching (the testid
     *     changes), but the structural tier 3 selector would happily
     *     match it — and "clicking send" would abort the response.
     *
     *   - A disabled button cannot be clicked, so returning one would
     *     make send() report success while doing nothing.
     *
     * @returns {{element: HTMLElement, selector: string, tier: number}|null}
     */
    findSendButton() {
      const chain = this.selectors.sendButton;

      for (let i = 0; i < chain.length; i++) {
        const element = document.querySelector(chain[i]);
        if (!element) continue;

        if (element.disabled) continue;
        if (element.offsetParent === null) continue;         // hidden
        if (element.dataset?.testid === "stop-button") continue;

        // Belt and braces for the structural tiers: the stop control
        // is labelled, so check the accessible name too.
        const label = (element.getAttribute("aria-label") ?? "").toLowerCase();
        if (label.includes("stop")) continue;

        return { element, selector: chain[i], tier: i + 1 };
      }

      return null;
    },

    /**
     * Send whatever is currently in the composer.
     *
     * Note what this function does NOT do: it does not write the text
     * back. We cancelled the send EVENT, never the text — the user's
     * message is still in the box and React's internal state already
     * holds it, because React saw every keystroke and we never
     * interfered with those. Replay is therefore "trigger the send
     * again", not "reconstruct the message".
     *
     * (Week 5's `redact` action is the one case where we do change
     * the text before sending. That needs the native-value-setter
     * workaround for React's controlled inputs, and is deliberately
     * not built yet.)
     *
     * Both routes below dispatch events with isTrusted === false, so
     * our own interceptor's synthetic-event guard lets them through.
     * That is why replay needs no "am I replaying?" state flag.
     *
     * @param {HTMLElement} composer
     * @returns {{method: string, detail: string}}
     */
    send(composer) {
      // ---- Primary: click the platform's own button --------------
      // Using the app's real send path means everything ChatGPT does
      // on send — clearing the box, optimistic UI, scrolling,
      // analytics — happens exactly as it normally would. React fires
      // onClick for dispatched clicks; it never checks isTrusted.
      const button = this.findSendButton();

      if (button) {
        button.element.click();
        return { method: "button-click", detail: button.selector };
      }

      // ---- Fallback: synthetic Enter -----------------------------
      // Reached when the button is missing, disabled, or the markup
      // moved. Less reliable because it assumes their handler is on
      // keydown, but better than having no way through at all.
      composer.focus();

      composer.dispatchEvent(
        new KeyboardEvent("keydown", {
          key: "Enter",
          code: "Enter",

          // Deprecated, but plenty of production handlers still read
          // them. Chrome honours these legacy members of
          // KeyboardEventInit; omitting them leaves both at 0, and a
          // handler checking `e.keyCode === 13` would ignore us.
          keyCode: 13,
          which: 13,

          // Essential. React attaches its listeners at the app root,
          // not on the composer — an event that does not bubble never
          // reaches them.
          bubbles: true,
          cancelable: true,
          composed: true,
        })
      );

      return { method: "synthetic-enter", detail: "send button not found" };
    },

    /**
     * Was this click inside the send button?
     *
     * The event target is almost never the button itself. The arrow
     * is a <button> wrapping an <svg> wrapping a <path>, and the
     * browser reports the innermost element under the cursor — so
     * `target.matches(buttonSelector)` is false essentially always,
     * and fails silently forever.
     *
     * closest() walks UP from the target through its ancestors and
     * returns the first match, which finds the button no matter how
     * deep in its internals the user clicked.
     *
     * We walk the tiers individually rather than passing one
     * comma-joined selector list so that the caller can report WHICH
     * tier matched — the same early-warning signal the composer
     * watcher provides.
     *
     * @param {EventTarget} target  usually event.target
     * @returns {{element: HTMLElement, selector: string, tier: number}|null}
     */
    matchSendButton(target) {
      // Text nodes and the document itself have no closest().
      if (typeof target?.closest !== "function") return null;

      const chain = this.selectors.sendButton;

      for (let i = 0; i < chain.length; i++) {
        const element = target.closest(chain[i]);
        if (element) return { element, selector: chain[i], tier: i + 1 };
      }

      return null;
    },

    /**
     * Extract the user's text from the composer element.
     *
     * The textarea/contenteditable split matters more than it looks:
     *
     *   <textarea>        → .value holds a plain string with "\n"
     *   contenteditable   → .value is undefined; the text lives in
     *                       child nodes, one <p> per visual line
     *
     * For the contenteditable case we use innerText, NOT textContent.
     * textContent concatenates raw text nodes and ignores layout, so
     *
     *     <p>sk-proj-abc</p><p>def123</p>
     *
     * becomes "sk-proj-abcdef123" — two separate lines fused into one
     * string that looks exactly like a single API key. innerText
     * respects block boundaries and yields "sk-proj-abc\ndef123".
     *
     * That distinction directly changes what Stage 1's regex sees, so
     * it is a detection-accuracy decision, not a formatting nicety.
     *
     * @param {HTMLElement} element
     * @returns {string}
     */
    readText(element) {
      if (!element) return "";

      // A <textarea> exposes .value; a contenteditable div does not.
      if (typeof element.value === "string") {
        return element.value;
      }

      return element.innerText ?? "";
    },

    /**
     * Is the composer effectively empty?
     *
     * ProseMirror never leaves the editor truly blank — it keeps a
     * placeholder <p><br></p> so the caret has somewhere to live.
     * Its innerText is "\n", which is truthy and non-zero-length.
     * A naive `text.length > 0` check therefore reports "the user
     * typed something" on a completely empty box, which in Week 2
     * would mean firing a backend analysis on every focus event.
     *
     * @param {HTMLElement} element
     * @returns {boolean}
     */
    isEmpty(element) {
      return this.readText(element).trim().length === 0;
    },
  });
})();
